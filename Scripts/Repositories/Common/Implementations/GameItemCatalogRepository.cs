    public async Task<List<GameItemCatalog>> GetGameItemCatalogSimpleAsync()
    {
        List<GameItemCatalog> gameItemCatalogs = new List<GameItemCatalog>();
        string connectionString = DatabaseConfig.ConnectionString;

        await using (MySqlConnection connection = new MySqlConnection(connectionString))
        {
            try
            {
                await connection.OpenAsync();

                string selectSQL = @"
                SELECT object_id, object_type, name, image, rare, quality
                FROM game_item_catalog 
                WHERE 1=1";

                await using (MySqlCommand selectCommand = new MySqlCommand(selectSQL, connection))
                {

                    await using (MySqlDataReader reader = await selectCommand.ExecuteReaderAsync())
                    {
                        while (await reader.ReadAsync())
                        {
                            GameItemCatalog gameItemCatalog = new GameItemCatalog
                            {
                                ObjectId = reader.GetStringSafe("object_id"),
                                ObjectType = reader.GetStringSafe("object_type"),
                                Name = reader.GetStringSafe("name"),
                                Image = reader.GetStringSafe("image"),
                                Rarity = reader.GetStringSafe("rare"),
                                Quality = reader.GetDoubleSafe("quality"),
                            };

                            gameItemCatalogs.Add(gameItemCatalog);
                        }
                    }
                }
            }
            catch (MySqlConnector.MySqlException ex)
            {
                Debug.LogError("Error: " + ex.Message);
            }
            finally
            {
                await connection.CloseAsync();
            }
        }

        return gameItemCatalogs;
    }
